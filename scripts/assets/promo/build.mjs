#!/usr/bin/env node
// The promotional images (SPEC-059 §4.6.3): the link preview and the install
// sheet's three screenshots. Plain Node and Playwright's Chromium — the
// browser the e2e suite already installs (`npx playwright install chromium`),
// so there is no new dependency. It runs by hand and is never part of
// `npm run check`:
//
//   npm run dev                                  # in another terminal
//   node scripts/assets/promo/build.mjs [og] [screenshots]
//
// - `og`: `scripts/assets/promo/og.html` at 1200 × 630 → `public/og.png`.
// - `screenshots`: against a running dev server (`BASE_URL`, default
//   `http://localhost:5173`), 1280 × 720 JPEGs at quality 82 after 8 s of play,
//   the version label hidden: Cinder-4 and Thessaly on the keyboard scheme
//   (`wide-1.jpg`, `wide-2.jpg`), Vetra under touch emulation with the thumb
//   arc showing (`narrow-1.jpg`).
//
// Both write their `LICENSES.md` rows, relative to `public/` like the icons,
// under `## Promotional images (outside the precache)`. None of the four is
// precached (`PWA_OPTIONS.workbox.globIgnores`); `scripts/assets/check.mjs`
// reports them on their own `promo` line.
import { mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const require = createRequire(import.meta.url);
const HERE = dirname(fileURLToPath(import.meta.url));
const PUBLIC = join(HERE, '..', '..', '..', 'public');
const LICENSES = join(PUBLIC, 'assets', 'LICENSES.md');
const BASE_URL = process.env.BASE_URL ?? 'http://localhost:5173';
const PLAY_MS = 8_000;
const JPEG_QUALITY = 82;

/** The four files, relative to `public/`, and what each row says it is. */
const FILES = [
  ['og.png', 'the link preview: the prologue’s Selection wall under the wordmark, 1200 × 630, from `scripts/assets/promo/og.html`'],
  ['screenshots/wide-1.jpg', 'a salvager on Cinder-4, captured from the game at 1280 × 720'],
  ['screenshots/wide-2.jpg', 'the ruins of Thessaly, captured from the game at 1280 × 720'],
  ['screenshots/narrow-1.jpg', 'Vetra under touch emulation with the thumb arc showing, captured from the game at 1280 × 720'],
];

const HEADING = '## Promotional images (outside the precache)';

/** §4.6.3: the section of rows, rewritten in place on every run. */
function writeLicenseRows() {
  const text = readFileSync(LICENSES, 'utf8');
  const section = [
    HEADING,
    '',
    'The link preview and the install sheet’s screenshots live outside this folder,',
    'directly under `public/`, and stay out of the service worker’s precache',
    '(SPEC-059 §4.6.4): crawlers and install sheets fetch them, offline play never',
    'does. `node scripts/assets/promo/build.mjs` writes all four by hand — the',
    'preview from a template over the prologue’s poster, the screenshots from a',
    'running dev server — and `scripts/assets/check.mjs` reports them on their own',
    '`promo` line, with a 2 MB budget.',
    '',
    '| File | Source | License | Modifications |',
    '| --- | --- | --- | --- |',
    ...FILES.map(([file, what]) => `| \`${file}\` | Original to this repository — ${what}; generated by \`scripts/assets/promo/build.mjs\` | CC0 | — |`),
    '',
  ].join('\n');
  const at = text.indexOf(HEADING);
  const next = at < 0 ? -1 : text.indexOf('\n## ', at + HEADING.length);
  const out = at < 0 ? `${text.trimEnd()}\n\n${section}` : `${text.slice(0, at)}${section}${next < 0 ? '' : text.slice(next + 1)}`;
  writeFileSync(LICENSES, out);
}

const kb = (path) => `${(statSync(path).size / 1024).toFixed(0)} KB`;

/** §4.6.3: the template, screenshotted. */
async function buildOg(browser) {
  const page = await browser.newPage({ viewport: { width: 1200, height: 630 }, deviceScaleFactor: 1 });
  await page.goto(pathToFileURL(join(HERE, 'og.html')).href);
  await page.waitForLoadState('load');
  await page.evaluate(() => document.fonts.ready);
  const out = join(PUBLIC, 'og.png');
  await page.screenshot({ path: out, type: 'png' });
  await page.close();
  console.log(`og.png                  ${kb(out)}`);
}

/** One landing, played for 8 s and captured with the version label hidden. */
async function capture(browser, planet, file, touch) {
  const context = await browser.newContext({
    viewport: { width: 1280, height: 720 },
    deviceScaleFactor: 1,
    hasTouch: touch,
  });
  const page = await context.newPage();
  await page.goto(`${BASE_URL}/?scene=surface&planet=${planet}&seed=62&quality=high`);
  const gate = page.locator('[data-testid="boot-start"]');
  await gate.waitFor({ state: 'visible', timeout: 60_000 });
  await gate.click();
  await page.waitForFunction(() => window.__reallm?.scene() === 'surface', undefined, { timeout: 60_000 });
  await page.waitForFunction(() => getComputedStyle(document.querySelector('[data-testid="transition-fade"]') ?? document.body).pointerEvents === 'none');
  // The thumbs: a tap on the screen flips the scheme, and the arc shows.
  if (touch) await page.touchscreen.tap(640, 360);
  await page.waitForTimeout(PLAY_MS);
  await page.addStyleTag({ content: '[data-testid="version-label"] { visibility: hidden !important; }' });
  const out = join(PUBLIC, file);
  mkdirSync(dirname(out), { recursive: true });
  await page.screenshot({ path: out, type: 'jpeg', quality: JPEG_QUALITY });
  await context.close();
  console.log(`${file.padEnd(24)}${kb(out)}`);
}

const only = new Set(process.argv.slice(2));
const want = (part) => only.size === 0 || only.has(part);
const { chromium } = require('@playwright/test');
const browser = await chromium.launch();
try {
  if (want('og')) await buildOg(browser);
  if (want('screenshots')) {
    await capture(browser, 'cinder4', 'screenshots/wide-1.jpg', false);
    await capture(browser, 'thessaly', 'screenshots/wide-2.jpg', false);
    await capture(browser, 'vetra', 'screenshots/narrow-1.jpg', true);
  }
  writeLicenseRows();
} finally {
  await browser.close();
}
